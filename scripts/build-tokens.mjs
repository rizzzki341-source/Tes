// Turns replica/design/tokens.json into src/styles/tokens.css (CSS custom properties).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const source = new URL('../replica/design/tokens.json', import.meta.url);
const target = new URL('../src/styles/tokens.css', import.meta.url);
const tokens = JSON.parse(readFileSync(source, 'utf8'));

const px = (n) => `${n}px`;
// Type sizes are emitted in rem so they follow the reader's font-size setting.
const rem = (n) => `${Number((n / 16).toFixed(4))}rem`;

const lines = [];
const group = (title, entries) => {
  lines.push(`  /* ${title} */`);
  for (const [name, value] of entries) lines.push(`  --${name}: ${value};`);
  lines.push('');
};

group('color', Object.entries(tokens.color).map(([role, hex]) => [`color-${role}`, hex]));
group('font', Object.entries(tokens.font).map(([name, stack]) => [`font-${name}`, stack]));
group(
  'type',
  Object.entries(tokens.type).flatMap(([name, t]) => [
    [`type-${name}-size`, rem(t.size)],
    [`type-${name}-line`, rem(t.line)],
    [`type-${name}-weight`, t.weight],
  ]),
);
group('space', tokens.space.map((value, index) => [`space-${index}`, px(value)]));
group('radius', Object.entries(tokens.radius).map(([name, value]) => [`radius-${name}`, px(value)]));
group('shadow', Object.entries(tokens.shadow).map(([name, value]) => [`shadow-${name}`, value]));
group('motion', Object.entries(tokens.motion).map(([name, value]) => [`motion-${name}`, value]));
group('layout', Object.entries(tokens.layout).map(([name, value]) => [`layout-${name}`, px(value)]));
while (lines.at(-1) === '') lines.pop();

const css = `/* Generated by scripts/build-tokens.mjs from replica/design/tokens.json. Do not edit. */
:root {
${lines.join('\n')}
}
`;

mkdirSync(dirname(fileURLToPath(target)), { recursive: true });
writeFileSync(target, css);
console.log(`tokens: wrote ${fileURLToPath(target)}`);
